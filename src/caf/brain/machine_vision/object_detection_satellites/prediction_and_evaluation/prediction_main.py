from pathlib import Path
import logging

from caf.brain.machine_vision.object_detection_satellites.prediction_and_evaluation.prediction_evaluation_functions import \
    prediction, extract_results
from caf.brain.machine_vision.object_detection_satellites.yolo_modelling.data_processing.build_yolo_config import \
    build_prediction_config

LOG = logging.getLogger(__name__)
import os


def main_prediction(prediction_images_folder: Path,
                    output: Path,
                    class_names: list[str],
                    model_path: Path = None) -> None:
    # todo model_path should instead be database link
    if model_path is None:
        raise ValueError("Model_path is none. This is required in order to run \
                         the model. If you ran the model build it should be located \
                         inside a folder your_out_path\ModelBuildingOutputs\model_results\best.pt. \
                         This is generated when the model is trained which is what \
                         you are using for your predictions. If you did not \
                         run the model build then it should be located DATABASE LINK")

    if output is None:
        raise ValueError("Please provide an output path. This should be a \
                          location on your computers drive e.g. E:\Documents")

    if prediction_images_folder is None:
        raise ValueError("Please provide a path to where your images are stored. \
                          these should have been generated by the generate images \
                          portion of this package.")

    if class_names is None:
        raise ValueError("Please provide a list of class_names to the input \
                          config file. These are the names of what you are \
                          trying to predict. If you ran the build_model portion \
                          of this package then these names should be passed in \
                          the exact same order.")

    model_dir = os.path.join(output, 'ObjectDetectionResults')
    os.makedirs(model_dir, exist_ok=True)

    build_prediction_config(output=model_dir,
                            class_names=class_names)

    prediction_results_dir, model = prediction(output=model_dir,
                                               final_model_path=model_path)

    extract_results(prediction_results_dir=prediction_results_dir,
                    model=model)


    return
